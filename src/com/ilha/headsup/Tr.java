    static String[] frags, fragsEs;

    /** 0 = automático (idioma do aparelho), 1 = português, 2 = inglês, 3 = espanhol. */
    static void setup(int choice) {
        String l = java.util.Locale.getDefault().getLanguage();
        es = choice == 3 || (choice == 0 && "es".equals(l));
        en = es || choice == 2 || (choice == 0 && !"pt".equals(l));
    }

    static String[] fragsOf(java.util.HashMap<String, String> m) {
        java.util.ArrayList<String> f = new java.util.ArrayList<>();
        for (String k : m.keySet()) if (k.length() >= 5) f.add(k);
        java.util.Collections.sort(f, new java.util.Comparator<String>() {
            public int compare(String a, String b) {
                return b.length() - a.length();
            }
        });
        return f.toArray(new String[0]);
    }

    static String t(String s) {
        if (!en || s == null) return s;
        java.util.HashMap<String, String> m = es ? E : M;
        String r = m.get(s);
        if (r == null && es) r = M.get(s);   // sem tradução em espanhol: inglês
        if (r != null) return r;
        if (es && fragsEs == null) fragsEs = fragsOf(E);
        if (frags == null) frags = fragsOf(M);
        String o = s;
        if (es) for (String k : fragsEs) if (o.contains(k)) o = o.replace(k, E.get(k));
        for (String k : frags) if (o.contains(k)) o = o.replace(k, M.get(k));
        return o;
    }

